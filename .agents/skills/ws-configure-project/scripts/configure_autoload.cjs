const ABS_PATH_RE = /(?:(?<![A-Za-z0-9])[A-Za-z]:[\\/]|\\\\[^\\\s`"']+|\/(?:Users|home|opt)\/)/;
const SKILL_ROW_RE = /^\|\s*`(ws-[a-z0-9-]+)`\s*\|\s*([^|]+)\|\s*([^|]+)\|\s*$/;

function defaultRepoRoot() {
  return path.resolve(process.cwd());
}

const GENERATED_MARKER = '<!-- generated by configure_autoload.cjs -->';
const SHARED_CONFIG_REL = path.join('.ws', 'config.json');
const SHARED_CONFIG_EXAMPLE_REL = path.join('.agents', 'skills', 'ws-shared', 'templates', 'config.json.example');
const SHARED_AUTOLOAD_REL = path.join('.ws', 'autoload.md');
const SHARED_RUNTIME_REL = path.join('.agents', 'skills', 'ws-shared', 'runtime');

function knownGlobalSkillsRoots() {
  const home = os.homedir();
  const roots = [
    resolveGlobalSkillsRoot(null),
    path.resolve(home, '.agents', 'skills'),
    path.resolve(home, '.claude', 'skills'),
    path.resolve(home, '.codex', 'skills'),
    path.resolve(home, '.gemini', 'config', 'skills'),
  ];
  return [...new Set(roots)];
}

function isGlobalSkillsRoot(p) {
  const resolved = path.resolve(p);
  return knownGlobalSkillsRoots().some((r) => r === resolved);
}

function loadConfigJson(repoRoot) {
  const p = path.join(repoRoot, SHARED_CONFIG_REL);
  if (!fs.existsSync(p)) return null;
  try {
    const data = JSON.parse(fs.readFileSync(p, 'utf8'));
    if (!data || typeof data !== 'object') return null;
    return data;
  } catch { return null; }
}

function resolveEffectiveAutoload(repoRoot) {
  const data = loadConfigJson(repoRoot);
  if (!data) return false;
  const defaults = data.defaults;
  if (!defaults || typeof defaults !== 'object') return false;
  return defaults.autoload === true;
}

function resolveAutoloadTaskLifecycle(repoRoot) {
  const data = loadConfigJson(repoRoot);
  if (!data) return true;
  const defaults = data.defaults;
  if (!defaults || typeof defaults !== 'object') return true;
  if (!('autoloadTaskLifecycle' in defaults)) return true;
  return defaults.autoloadTaskLifecycle !== false;
}

const TASK_LIFECYCLE_ID = 'ws-task-lifecycle';
const TASK_LIFECYCLE_TRIGGER = 'Every prompt-driven product task — intake, implement, complete (required)';

function ensureTaskLifecycleMember(membership) {
  if (membership.some((r) => r.skill === TASK_LIFECYCLE_ID)) return membership;
  return [...membership, { skill: TASK_LIFECYCLE_ID, trigger: TASK_LIFECYCLE_TRIGGER }];
}

function dropTaskLifecycleMember(membership) {
  return membership.filter((r) => r.skill !== TASK_LIFECYCLE_ID);
}

function setAutoloadTaskLifecycle(repoRoot, value, dryRun = false, examplePath = null) {
  const configPath = path.join(repoRoot, SHARED_CONFIG_REL);
  examplePath = examplePath || path.join(repoRoot, SHARED_CONFIG_EXAMPLE_REL);
  let createdFromExample = false;
  if (!fs.existsSync(configPath)) {
    if (!fs.existsSync(examplePath)) {
      console.error(`ERROR: missing ${configPath} and example ${examplePath} (install hub / copy template)`);
      process.exit(1);
    }
    if (!dryRun) {
      fs.mkdirSync(path.dirname(configPath), { recursive: true });
      fs.copyFileSync(examplePath, configPath);
    }
    createdFromExample = true;
  }
  let data = loadConfigJson(repoRoot);
  if (!data && dryRun && createdFromExample) {
    try { data = JSON.parse(fs.readFileSync(examplePath, 'utf8')); } catch { data = null; }
  }
  if (!data) {
    console.error(`ERROR: could not read or parse ${configPath}`);
    process.exit(1);
  }
  if (!data.defaults || typeof data.defaults !== 'object') data.defaults = {};
  data.defaults.autoloadTaskLifecycle = Boolean(value);
  let written = false;
  if (!dryRun) {
    fs.writeFileSync(configPath, JSON.stringify(data, null, 2) + '\n', 'utf8');
    written = true;
  }
  return { configPath, autoloadTaskLifecycle: Boolean(value), autoload: data.defaults.autoload, written, createdFromExample };
}

