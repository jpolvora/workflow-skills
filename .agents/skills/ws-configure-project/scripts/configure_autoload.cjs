function resolveGlobalSkillsRoot(explicit) {
  if (explicit) return path.resolve(String(explicit).replace(/^~(?=$|[\\/])/, os.homedir()));
  const env = (process.env.WORKFLOW_SKILLS_GLOBAL_DIR || '').trim();
  if (env) return path.resolve(env.replace(/^~(?=$|[\\/])/, os.homedir()));
  return path.resolve(os.homedir(), '.agents', 'skills');
}

function resolveExecutionGlobalSkillsRoot(explicit) {
  if (explicit) return resolveGlobalSkillsRoot(explicit);
  const scriptPath = path.resolve(__filename);
  for (const root of knownGlobalSkillsRoots()) {
    if (scriptPath === root || scriptPath.startsWith(root + path.sep)) return root;
  }
  return resolveGlobalSkillsRoot(null);
}

function scriptIsGlobalSkillsInstall() {
  const scriptPath = path.resolve(__filename);
  return knownGlobalSkillsRoots().some((root) => scriptPath === root || scriptPath.startsWith(root + path.sep));
}

function resolveRuntimeSource(repoRoot, globalSkillsRoot, allowGlobalSource = false) {
  const local = path.join(repoRoot, SHARED_RUNTIME_REL);
  if (fs.existsSync(local)) return local;
  if (!allowGlobalSource && !scriptIsGlobalSkillsInstall()) return local;
  return path.join(globalSkillsRoot, 'ws-shared', 'runtime');
}

function resolveTemplateSource(repoRoot, globalSkillsRoot, allowGlobalSource = false) {
  const local = path.join(repoRoot, path.dirname(SHARED_CONFIG_EXAMPLE_REL));
  if (fs.existsSync(local)) return local;
  if (!allowGlobalSource && !scriptIsGlobalSkillsInstall()) return local;
  return path.join(globalSkillsRoot, 'ws-shared', 'templates');
}

function emitSkillPath(repoRoot, skillId, { skillsRootRel = '.agents/skills', globalSkillsRoot = null } = {}) {
  const localSkill = path.join(repoRoot, skillsRootRel, skillId, 'SKILL.md');
  if (fs.existsSync(localSkill)) return [`.agents/skills/${skillId}/SKILL.md`, false];
  const groot = globalSkillsRoot || resolveGlobalSkillsRoot(null);
  if (fs.existsSync(path.join(groot, skillId, 'SKILL.md'))) return [`{globalSkillsRoot}/${skillId}/SKILL.md`, false];
  return [`{skillsRoot}/${skillId}/SKILL.md`, true];
}

function loadExternalSkillIds(repoRoot, { globalSkillsRoot = null, allowGlobalSource = false } = {}) {
  const candidates = [path.join(repoRoot, 'bin', 'skill-dependencies.json')];
  const runtime = resolveRuntimeSource(repoRoot, globalSkillsRoot || resolveExecutionGlobalSkillsRoot(null), allowGlobalSource);
  candidates.push(path.join(runtime, 'skill-dependencies.json'));
  for (const candidate of candidates) {
    if (!fs.existsSync(candidate)) continue;
    let data;
    try { data = JSON.parse(fs.readFileSync(candidate, 'utf8')); } catch { continue; }
    const raw = data.externalSkills || [];
    if (!Array.isArray(raw)) continue;
    const ids = new Set();
    for (const item of raw) {
      if (typeof item === 'string' && item.startsWith('ws-')) ids.add(item);
      else if (item && typeof item === 'object') {
        const sid = String(item.id || '').trim();
        if (sid.startsWith('ws-')) ids.add(sid);
      }
    }
    return ids;
  }
  return new Set();
}

function dropExternalCompanionMembers(membership, repoRoot, { globalSkillsRoot = null, allowGlobalSource = false } = {}) {
  const external = loadExternalSkillIds(repoRoot, { globalSkillsRoot, allowGlobalSource });
  if (!external.size) return membership;
  return membership.filter((row) => !external.has(row.skill));
}

function renderConsumerAutoload(text) {
  for (const f of ['AGENTS.md', 'CROSS-PLATFORM.md', 'config-resolution.md', 'gates.md', 'host-dispatch.md', 'scm-provider-contract.md', 'setup.md', 'tools.md']) {
    text = text.split(`](${f})`).join(`](../.agents/skills/ws-shared/runtime/${f})`);
  }
  return text.replace(/\]\(\.\.\/\.\.\/(ws-[^)]+)\)/g, '](../.agents/skills/$1)');
}

function defaultAlwaysAppliedMembership() {
  return DEFAULT_ALWAYS_APPLIED.map(([skill, trigger]) => ({ skill, trigger }));
}

function membershipFromExistingRows(rows) {
  const out = [];
  const seen = new Set();
  for (const row of rows) {
    const skillId = String(row.skill || '').trim();
    if (!skillId.startsWith('ws-') || seen.has(skillId)) continue;
    seen.add(skillId);
    out.push({ skill: skillId, trigger: String(row.trigger || '').trim() || 'Every prompt' });
  }
  return out;
}

function buildAlwaysAppliedTable(repoRoot, { globalSkillsRoot = null, membership = null } = {}) {
  const rows = ['| Skill | Path | Trigger|', '|-------|------|---------|'];
  // Note: header row below is normalized by the writer; keep exact canonical form:
  rows[0] = '| Skill | Path | Trigger |';
  const meta = [];
  const members = membership !== null ? membership : defaultAlwaysAppliedMembership();
  for (const member of members) {
    const [pathForm, missing] = emitSkillPath(repoRoot, member.skill, { globalSkillsRoot });
    rows.push(`| \`${member.skill}\` | \`${pathForm}\` | ${member.trigger} |`);
    meta.push({ skill: member.skill, path: pathForm, missing, trigger: member.trigger });
  }
  return [rows.join('\n') + '\n', meta];
}

function ensureAutoloadMd(repoRoot, { globalSkillsRoot = null, allowGlobalSource = false, dryRun = false } = {}) {
  const autoloadPath = path.join(repoRoot, SHARED_AUTOLOAD_REL);
  let source = null;
  if (!fs.existsSync(autoloadPath)) {
    const runtime = resolveRuntimeSource(repoRoot, globalSkillsRoot || resolveExecutionGlobalSkillsRoot(null), allowGlobalSource);
    source = path.join(runtime, 'autoload.md');
    if (!fs.existsSync(source)) {
      console.error(`ERROR: missing ${source} (install hub runtime)`);
      process.exit(1);
    }
    if (!dryRun) {
      fs.mkdirSync(path.dirname(autoloadPath), { recursive: true });
      fs.writeFileSync(autoloadPath, renderConsumerAutoload(fs.readFileSync(source, 'utf8')), 'utf8');
    }
  }
  const text = renderConsumerAutoload(fs.existsSync(autoloadPath) ? fs.readFileSync(autoloadPath, 'utf8') : fs.readFileSync(source, 'utf8'));
  const existing = parseAlwaysAppliedRows(text);
  const preserved = membershipFromExistingRows(existing);
  let membership = preserved.length ? preserved : defaultAlwaysAppliedMembership();
  membership = dropExternalCompanionMembers(membership, repoRoot, { globalSkillsRoot, allowGlobalSource });
  membership = resolveAutoloadTaskLifecycle(repoRoot) ? ensureTaskLifecycleMember(membership) : dropTaskLifecycleMember(membership);
  const [table, meta] = buildAlwaysAppliedTable(repoRoot, { globalSkillsRoot, membership });
  const pattern = /(## Always-applied skills\r?\n(?:.*\r?\n)*?)(\| Skill \| Path \| Trigger \|\r?\n\|[-| ]+\|\r?\n(?:\|[^\r\n]*\|\r?\n)+)/;
  const match = pattern.exec(text);
  if (!match) {
    console.error('ERROR: could not find Always-applied skills table in autoload.md');
    process.exit(1);
  }
  let newText = text.slice(0, match.index + match[1].length) + table + text.slice(match.index + match[0].length);
  if (newText.includes('ws-configure-project') && newText.includes('when that section is implemented')) {
    newText = newText.split('Customize the Always-applied table per project when needed (or via `ws-configure-project` when that section is implemented).').join('Customize the Always-applied table per project when needed (or via `ws-configure-project --section autoload`).');
  }
  let written = false;
  if (newText !== text && !dryRun) {
    fs.writeFileSync(autoloadPath, newText, 'utf8');
    written = true;
  }
  return { autoloadPath, written, changed: newText !== text, skills: meta, preservedMembership: Boolean(preserved.length) };
}

