function writeRootAgents(repoRoot, { globalSkillsRoot = null, allowGlobalSource = false, dryRun = false, force = false } = {}) {
  const sharedAutoload = path.join(repoRoot, '.ws', 'autoload.md');
  let membership = defaultAlwaysAppliedMembership();
  if (fs.existsSync(sharedAutoload)) {
    const preserved = membershipFromExistingRows(parseAlwaysAppliedRows(fs.readFileSync(sharedAutoload, 'utf8')));
    if (preserved.length) membership = preserved;
  }
  membership = dropExternalCompanionMembers(membership, repoRoot, { globalSkillsRoot, allowGlobalSource });
  const tableLines = ['| Skill | Path |', '|-------|------|'];
  const meta = [];
  for (const member of membership) {
    const [pathForm, missing] = emitSkillPath(repoRoot, member.skill, { globalSkillsRoot });
    tableLines.push(`| \`${member.skill}\` | \`${pathForm}\` |`);
    meta.push({ skill: member.skill, path: pathForm, missing });
  }
  const body = GENERATED_MARKER + '\n' + ROOT_AGENTS_TEMPLATE.replace('{table}', tableLines.join('\n'));
  if (containsAbsolutePath(body)) {
    console.error('ERROR: refused to write root AGENTS.md with absolute paths');
    process.exit(1);
  }
  const dest = path.join(repoRoot, 'AGENTS.md');
  let backedUp = false;
  if (fs.existsSync(dest)) {
    const existing = fs.readFileSync(dest, 'utf8');
    if (!existing.includes(GENERATED_MARKER)) {
      if (!force) {
        console.error('ERROR: root AGENTS.md exists and is not the generated thin pointer; pass --force to overwrite (a .bak copy is written)');
        process.exit(1);
      }
      if (!dryRun) {
        fs.copyFileSync(dest, dest + '.bak');
        backedUp = true;
      }
    }
  }
  const pointerPath = path.join(repoRoot, path.dirname(SHARED_AUTOLOAD_REL), 'AGENTS.md');
  let pointerWritten = false;
  if (!fs.existsSync(pointerPath)) {
    if (!dryRun) {
      fs.mkdirSync(path.dirname(pointerPath), { recursive: true });
      fs.writeFileSync(pointerPath, LOCAL_HUB_POINTER_MD, 'utf8');
      pointerWritten = true;
    }
  }
  let written = false;
  if (!dryRun) {
    fs.writeFileSync(dest, body, 'utf8');
    written = true;
  }
  return { rootAgentsPath: 'AGENTS.md', written, backedUp, hubPointerWritten: pointerWritten, skills: meta };
}

function containsAbsolutePath(text) {
  return String(text).split('\n').some((line) => ABS_PATH_RE.test(line));
}

function pathTargetsSkill(pathForm, skillId) {
  const normalized = String(pathForm).trim().replace(/\\/g, '/').replace(/\/+$/g, '');
  const noFile = normalized.endsWith('/SKILL.md') ? normalized.slice(0, -'/SKILL.md'.length) : normalized;
  return noFile.split('/').pop() === skillId;
}

function parseAlwaysAppliedRows(text) {
  const rows = [];
  const lines = String(text).split('\n');
  let inSection = false;
  for (const line of lines) {
    if (line.startsWith('## Always-applied')) { inSection = true; continue; }
    if (inSection && line.startsWith('## ')) break;
    if (!inSection) continue;
    const m = SKILL_ROW_RE.exec(line);
    if (!m) continue;
    rows.push({ skill: m[1], path: m[2].trim().replace(/^`|`$/g, '').trim(), trigger: m[3].trim() });
  }
  return rows;
}

function pathFormOk(pathForm) {
  if (containsAbsolutePath(`\`${pathForm}\``)) return false;
  if (pathForm.startsWith('{skillsRoot}/') || pathForm.startsWith('{globalSkillsRoot}/')) return true;
  if (pathForm.startsWith('.agents/skills/')) return true;
  return false;
}

function appendEffectiveAutoloadRootFindings(findings, { effective, rootAgents, rootText }) {
  if (!effective) return;
  const fix = 'Run ws-configure-project --section autoload';
  if (!fs.existsSync(rootAgents)) {
    findings.push({ severity: 'critical', file: 'AGENTS.md', message: 'defaults.autoload is true but root AGENTS.md is missing', fix });
    return;
  }
  const text = rootText !== null && rootText !== undefined ? rootText : fs.readFileSync(rootAgents, 'utf8');
  if (!text.includes('autoload.md')) {
    findings.push({ severity: 'critical', file: 'AGENTS.md', message: 'defaults.autoload is true but root AGENTS.md does not instruct loading Always-applied skills via autoload.md', fix });
  }
}

function checkAutoload(repoRoot, { globalSkillsRoot = null, allowGlobalSource = false } = {}) {
  const findings = [];
  const shared = path.join(repoRoot, '.ws');
  const autoloadPath = path.join(shared, 'autoload.md');
  const rootAgents = path.join(repoRoot, 'AGENTS.md');
  const effective = resolveEffectiveAutoload(repoRoot);
  const rootText = fs.existsSync(rootAgents) ? fs.readFileSync(rootAgents, 'utf8') : null;
  if (!fs.existsSync(autoloadPath)) {
    appendEffectiveAutoloadRootFindings(findings, { effective, rootAgents, rootText });
    const critical = findings.filter((f) => f.severity === 'critical').length;
    return { ok: critical === 0, findings, note: 'autoload.md absent — skip Always-applied path checks', rootAgentsPresent: fs.existsSync(rootAgents), effectiveAutoload: effective, autoloadPresent: false };
  }
  const text = fs.readFileSync(autoloadPath, 'utf8');
  if (containsAbsolutePath(text)) {
    findings.push({ severity: 'critical', file: '.ws/autoload.md', message: 'Absolute filesystem path detected; use relative or declared tokens only', fix: 'Run ws-configure-project --section autoload / configure_autoload.cjs --write-autoload' });
  }
  for (const row of parseAlwaysAppliedRows(text)) {
    if (loadExternalSkillIds(repoRoot, { globalSkillsRoot, allowGlobalSource }).has(row.skill)) {
      findings.push({ severity: 'warning', file: '.ws/autoload.md', message: `Always-applied lists external companion \`${row.skill}\` (not packaged here); move to External companion skills and skip when absent`, fix: 'Remove the Always-applied row; keep the optional companion section' });
      continue;
    }
    if (!pathFormOk(row.path)) {
      findings.push({ severity: 'warning', file: '.ws/autoload.md', message: `Always-applied path for \`${row.skill}\` is not portable: ${row.path}`, fix: 'Use `.agents/skills/...` or `{skillsRoot}` / `{globalSkillsRoot}` tokens' });
    } else if (!pathTargetsSkill(row.path, row.skill)) {
      findings.push({ severity: 'warning', file: '.ws/autoload.md', message: `Always-applied path for \`${row.skill}\` points at a different skill: ${row.path}`, fix: `Point the path at \`${row.skill}/SKILL.md\` (or run configure_autoload.cjs --write-autoload)` });
    }
    const local = path.join(repoRoot, '.agents', 'skills', row.skill, 'SKILL.md');
    const groot = globalSkillsRoot || resolveGlobalSkillsRoot(null);
    if (!fs.existsSync(local) && !fs.existsSync(path.join(groot, row.skill, 'SKILL.md'))) {
      findings.push({ severity: 'warning', file: '.ws/autoload.md', message: `Always-applied skill \`${row.skill}\` missing under skillsRoot and globalSkillsRoot`, fix: `Install \`${row.skill}\` or remove the Always-applied row` });
    }
  }
  if (rootText !== null) {
    if (containsAbsolutePath(rootText)) {
      findings.push({ severity: 'critical', file: 'AGENTS.md', message: 'Absolute filesystem path detected in root AGENTS.md', fix: 'Regenerate via configure_autoload.cjs --write-root-agents' });
    }
  }
  appendEffectiveAutoloadRootFindings(findings, { effective, rootAgents, rootText });
  const critical = findings.filter((f) => f.severity === 'critical').length;
  return {
    ok: critical === 0,
    findings,
    rootAgentsPresent: fs.existsSync(rootAgents),
    autoloadPresent: true,
    effectiveAutoload: effective,
    dualHubOverrideOk: (!fs.existsSync(rootAgents)) || (rootText !== null && rootText.includes('autoload.md')),
  };
}

function printHelp() {
  console.log('Usage: node configure_autoload.cjs [--repo-root DIR] [--global-skills-root DIR] [--write-autoload] [--write-root-agents] [--check] [--emit-paths] [--set-autoload true|false] [--set-autoload-task-lifecycle true|false] [--dry-run] [--force] [--json]');
}

function parseArgs(argv) {
  const o = { repoRoot: null, globalSkillsRoot: null, writeAutoload: false, writeRootAgents: false, check: false, emitPaths: false, setAutoload: null, setAutoloadTaskLifecycle: null, dryRun: false, force: false, json: false };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === '--help' || a === '-h') { printHelp(); process.exit(0); }
    else if (a === '--repo-root') o.repoRoot = argv[++i];
    else if (a.startsWith('--repo-root=')) o.repoRoot = a.slice(12);
    else if (a === '--global-skills-root') o.globalSkillsRoot = argv[++i];
    else if (a.startsWith('--global-skills-root=')) o.globalSkillsRoot = a.slice(20);
    else if (a === '--write-autoload') o.writeAutoload = true;
    else if (a === '--write-root-agents') o.writeRootAgents = true;
    else if (a === '--check') o.check = true;
    else if (a === '--emit-paths') o.emitPaths = true;
    else if (a === '--set-autoload') o.setAutoload = argv[++i];
    else if (a.startsWith('--set-autoload=')) o.setAutoload = a.slice(15);
    else if (a === '--set-autoload-task-lifecycle') o.setAutoloadTaskLifecycle = argv[++i];
    else if (a.startsWith('--set-autoload-task-lifecycle=')) o.setAutoloadTaskLifecycle = a.slice(30);
    else if (a === '--dry-run') o.dryRun = true;
    else if (a === '--force') o.force = true;
    else if (a === '--json') o.json = true;
    else { console.error(`unknown argument: ${a}`); process.exit(2); }
  }
  if (o.setAutoload !== null && !['true', 'false'].includes(o.setAutoload)) { console.error('argument --set-autoload: must be true|false'); process.exit(2); }
  if (o.setAutoloadTaskLifecycle !== null && !['true', 'false'].includes(o.setAutoloadTaskLifecycle)) { console.error('argument --set-autoload-task-lifecycle: must be true|false'); process.exit(2); }
  return o;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const repoRoot = args.repoRoot ? path.resolve(args.repoRoot) : defaultRepoRoot();
  const explicitGlobalRoot = args.globalSkillsRoot ? resolveGlobalSkillsRoot(args.globalSkillsRoot) : null;
  if (args.repoRoot === null && (isGlobalSkillsRoot(repoRoot) || (explicitGlobalRoot !== null && repoRoot === explicitGlobalRoot))) {
    console.error(`ERROR: current directory is a global skills root (${repoRoot}); pass --repo-root to target a consumer project`);
    process.exit(1);
  }
  const groot = resolveExecutionGlobalSkillsRoot(args.globalSkillsRoot);
  const allowGlobalSource = Boolean(args.globalSkillsRoot) || scriptIsGlobalSkillsInstall();
  const templateSource = resolveTemplateSource(repoRoot, groot, allowGlobalSource);
  const examplePath = path.join(templateSource, 'config.json.example');
  if (![args.writeAutoload, args.writeRootAgents, args.check, args.emitPaths, args.setAutoload !== null, args.setAutoloadTaskLifecycle !== null].some(Boolean)) {
    console.error('Choose --set-autoload, --set-autoload-task-lifecycle, --write-autoload, --write-root-agents, --check, or --emit-paths');
    process.exit(2);
  }
  const out = { repoRoot };
  if (args.emitPaths) {
    const [, meta] = buildAlwaysAppliedTable(repoRoot, { globalSkillsRoot: groot });
    out.skills = meta;
  }
  if (args.setAutoloadTaskLifecycle !== null) {
    out.setAutoloadTaskLifecycle = setAutoloadTaskLifecycle(repoRoot, args.setAutoloadTaskLifecycle === 'true', args.dryRun, examplePath);
  }
  if (args.writeAutoload) {
    out.autoload = ensureAutoloadMd(repoRoot, { globalSkillsRoot: groot, allowGlobalSource, dryRun: args.dryRun });
  }
  if (args.writeRootAgents) {
    out.rootAgents = writeRootAgents(repoRoot, { globalSkillsRoot: groot, allowGlobalSource, dryRun: args.dryRun, force: args.force });
  }
  if (args.setAutoload !== null) {
    out.setAutoload = setAutoload(repoRoot, args.setAutoload === 'true', args.dryRun, examplePath);
  }
  if (args.check) {
    out.check = checkAutoload(repoRoot, { globalSkillsRoot: groot, allowGlobalSource });
  }
  if (args.json) {
    console.log(JSON.stringify(out, null, 2));
  } else {
    if (out.setAutoload) {
      const s = out.setAutoload;
      console.log(`defaults.autoload=${s.autoload} written=${s.written} createdFromExample=${s.createdFromExample}`);
    }
    if (out.setAutoloadTaskLifecycle) {
      const t = out.setAutoloadTaskLifecycle;
      console.log(`defaults.autoloadTaskLifecycle=${t.autoloadTaskLifecycle} written=${t.written} createdFromExample=${t.createdFromExample}`);
    }
    if (args.emitPaths) {
      for (const row of out.skills || []) console.log(`${row.skill}: ${row.path}${row.missing ? ' MISSING' : ''}`);
    }
    if (out.autoload) console.log(`autoload: changed=${out.autoload.changed} written=${out.autoload.written}`);
    if (out.rootAgents) console.log(`root AGENTS.md: written=${out.rootAgents.written}`);
    if (out.check) {
      const c = out.check;
      console.log(`check ok=${c.ok} findings=${c.findings.length} effectiveAutoload=${c.effectiveAutoload}`);
      for (const f of c.findings) console.log(`  [${f.severity}] ${f.file}: ${f.message}`);
    }
  }
  if (args.check && !(out.check || {}).ok) process.exit(1);
  process.exit(0);
}

if (require.main === module) main();
module.exports = { checkAutoload, ensureAutoloadMd, writeRootAgents };

